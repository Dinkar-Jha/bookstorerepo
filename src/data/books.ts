// ─── Derived helpers ──────────────────────────────────────────────────────────

export const getFeaturedBooks = () => books.filter(b => b.featured)
export const getBestSellers = () => books.filter(b => b.bestSeller)
export const getNewArrivals = () => books.filter(b => b.newArrival)
export const getBookById = (id: string) => books.find(b => b.id === id)

export const getAllGenres = (): string[] =>
  [...new Set(books.map(b => b.genre))].sort()

export const getAllAuthors = (): string[] =>
  [...new Set(books.map(b => b.author))].sort()

export const getPriceRange = (): [number, number] => {
  const prices = books.map(b => b.price)
  return [Math.floor(Math.min(...prices)), Math.ceil(Math.max(...prices))]
}

export const getRelatedBooks = (bookId: string, limit = 4): Book[] => {
  const book = getBookById(bookId)
  if (!book) return []
  return books
    .filter(b => b.id !== bookId && b.genre === book.genre)
    .slice(0, limit)
}
